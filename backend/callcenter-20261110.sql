-- ============================================================================
-- Instituto Mara — Callcenters (10 nov 2026)
-- Se ejecuta DESPUÉS de todo lo de operadores (planes-operadores, llamadas,
-- comisiones, prueba-y-supervision, reasignar-operador). Se puede correr más de
-- una vez sin romper nada.
--
-- Lo que se acordó con Héctor (10/11/2026):
--   · Puede haber varios callcenters. Cada uno tiene un titular (también es
--     operador: llama y vende) que da de alta y desactiva a sus agentes.
--     Administración ve a todos y puede desactivar a cualquiera.
--   · Los operadores internos siguen exactamente igual (callcenter_id vacío).
--   · Administración asigna lotes al callcenter; el titular los reparte a mano o
--     parejo. Los prospectos del callcenter son exclusivos: nadie más los ve.
--   · Si un prospecto pasa 15 días sin ningún intento (y sin llamada agendada a
--     futuro), regresa solo a la bolsa de administración.
--   · Comisiones: mismo esquema (35 % primer pago, 5 % después). Se registran por
--     agente, pero el recibo se arma a nombre del callcenter (su titular) y el
--     titular ve el desglose. El agente del callcenter no ve montos de comisión.
--   · Descuento: tope general de Ajustes (10 %); el titular puede bajarlo por agente.
--   · Evaluación de llamadas con rúbrica: el titular evalúa a su equipo y
--     administración puede auditar cualquier llamada. Liga de grabación opcional.
--   · Bitácora de fichas abiertas y de cada movimiento de asignación.
--   · Metas opcionales del titular a cada agente (administración no pone metas).
--   · Privacidad: los operadores ya no pueden leer todas las membresías y regalos.
--   · Las solicitudes de prueba del sitio siguen yendo a operadores internos.
-- ============================================================================

-- 1. Tablas -------------------------------------------------------------------
create table if not exists callcenters (
  id uuid primary key default gen_random_uuid(),
  nombre text not null,
  activo boolean not null default true,
  notas text,
  creado_por uuid references perfiles(id) on delete set null default auth.uid(),
  creado_en timestamptz not null default now()
);
create unique index if not exists callcenters_nombre on callcenters (lower(nombre));
alter table callcenters enable row level security;

alter table operadores add column if not exists callcenter_id uuid references callcenters(id) on delete restrict;
alter table operadores add column if not exists es_titular boolean not null default false;
alter table operadores add column if not exists creado_por uuid references perfiles(id) on delete set null;
do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'operadores_titular_con_callcenter') then
    alter table operadores add constraint operadores_titular_con_callcenter check (not es_titular or callcenter_id is not null);
  end if;
end $$;
create unique index if not exists operadores_un_titular on operadores (callcenter_id) where es_titular;
create index if not exists operadores_callcenter on operadores (callcenter_id);

alter table prospectos add column if not exists callcenter_id uuid references callcenters(id) on delete set null;
alter table prospectos add column if not exists callcenter_en timestamptz;
create index if not exists prospectos_callcenter on prospectos (callcenter_id);

alter table prospecto_contactos add column if not exists grabacion text;   -- liga o ID de la grabación (opcional)

alter table ajustes add column if not exists callcenter_dias_caducidad int not null default 15;

alter table comision_cortes add column if not exists callcenter_id uuid references callcenters(id) on delete set null;

-- Cada movimiento de un prospecto entre administración, callcenters y agentes.
create table if not exists callcenter_movimientos (
  id uuid primary key default gen_random_uuid(),
  prospecto_id uuid not null references prospectos(id) on delete cascade,
  callcenter_id uuid references callcenters(id) on delete set null,
  operador_id uuid references operadores(id) on delete set null,     -- a quién quedó
  accion text not null check (accion in ('al_callcenter','repartido','a_bolsa','regresado','recuperado','a_operador')),
  nota text,
  por uuid references perfiles(id) on delete set null default auth.uid(),
  fecha timestamptz not null default now()
);
create index if not exists callcenter_mov_cc on callcenter_movimientos (callcenter_id, fecha desc);
create index if not exists callcenter_mov_p on callcenter_movimientos (prospecto_id, fecha desc);
alter table callcenter_movimientos enable row level security;

-- Fichas abiertas (quién vio los datos de qué prospecto y cuándo).
create table if not exists prospecto_consultas (
  id bigint generated by default as identity primary key,
  prospecto_id uuid not null references prospectos(id) on delete cascade,
  usuario_id uuid not null references perfiles(id) on delete cascade,
  operador_id uuid references operadores(id) on delete set null,
  fecha timestamptz not null default now()
);
create index if not exists prospecto_consultas_u on prospecto_consultas (usuario_id, fecha desc);
create index if not exists prospecto_consultas_op on prospecto_consultas (operador_id, fecha desc);
alter table prospecto_consultas enable row level security;

-- Evaluación de llamadas (rúbrica de 1 a 5).
create table if not exists llamada_evaluaciones (
  id uuid primary key default gen_random_uuid(),
  contacto_id uuid not null references prospecto_contactos(id) on delete cascade,
  prospecto_id uuid not null references prospectos(id) on delete cascade,
  operador_id uuid not null references operadores(id) on delete cascade,   -- a quien se evalúa
  evaluador_id uuid references perfiles(id) on delete set null default auth.uid(),
  tipo text not null check (tipo in ('titular','auditoria')),
  apertura smallint not null check (apertura between 1 and 5),
  guion smallint not null check (guion between 1 and 5),
  objeciones smallint not null check (objeciones between 1 and 5),
  cierre smallint not null check (cierre between 1 and 5),
  registro smallint not null check (registro between 1 and 5),
  total numeric generated always as (round((apertura + guion + objeciones + cierre + registro)::numeric / 5, 1)) stored,
  comentario text,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);
create unique index if not exists llamada_eval_unica on llamada_evaluaciones (contacto_id, tipo);
create index if not exists llamada_eval_op on llamada_evaluaciones (operador_id, creado_en desc);
alter table llamada_evaluaciones enable row level security;

-- Metas opcionales que el titular pone a cada agente.
create table if not exists callcenter_metas (
  operador_id uuid primary key references operadores(id) on delete cascade,
  llamadas_dia int check (llamadas_dia is null or llamadas_dia >= 0),
  conversaciones_semana int check (conversaciones_semana is null or conversaciones_semana >= 0),
  pruebas_mes int check (pruebas_mes is null or pruebas_mes >= 0),
  planes_mes int check (planes_mes is null or planes_mes >= 0),
  actualizado_por uuid references perfiles(id) on delete set null default auth.uid(),
  actualizado_en timestamptz not null default now()
);
alter table callcenter_metas enable row level security;

-- 2. ¿Quién consulta? -----------------------------------------------------------
-- Callcenter (activo) del operador que consulta; null para operadores internos.
create or replace function mi_callcenter() returns uuid
language sql stable security definer set search_path = public as $$
  select o.callcenter_id from operadores o join callcenters c on c.id = o.callcenter_id
   where o.usuario_id = auth.uid() and o.activo and c.activo limit 1;
$$;
create or replace function es_titular() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from operadores o join callcenters c on c.id = o.callcenter_id
                  where o.usuario_id = auth.uid() and o.activo and o.es_titular and c.activo);
$$;
-- ¿Este operador es del equipo del titular que consulta?
create or replace function es_de_mi_equipo(p_operador uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select es_titular() and exists (select 1 from operadores where id = p_operador and callcenter_id = mi_callcenter());
$$;
-- ¿Quien consulta es agente de un callcenter (no titular)? No ve montos de comisión.
create or replace function es_agente_callcenter() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from operadores where usuario_id = auth.uid() and activo and callcenter_id is not null and not es_titular);
$$;
grant execute on function mi_callcenter() to authenticated;
grant execute on function es_titular() to authenticated;
grant execute on function es_de_mi_equipo(uuid) to authenticated;
grant execute on function es_agente_callcenter() to authenticated;

-- 3. Permisos -----------------------------------------------------------------
drop policy if exists "callcenters lee" on callcenters;
create policy "callcenters lee" on callcenters for select using (es_admin() or id = mi_callcenter());
drop policy if exists "callcenters admin" on callcenters;
create policy "callcenters admin" on callcenters for all using (es_admin()) with check (es_admin());
grant select, insert, update, delete on callcenters to authenticated;

-- Operadores: el titular ve a su equipo (las altas y cambios van por funciones).
drop policy if exists "operadores lee" on operadores;
create policy "operadores lee" on operadores for select using (es_admin() or usuario_id = auth.uid() or es_de_mi_equipo(id));

-- Prospectos y su historial: el titular ve todo lo de su callcenter.
drop policy if exists "prospectos callcenter" on prospectos;
create policy "prospectos callcenter" on prospectos for select using (es_titular() and callcenter_id is not null and callcenter_id = mi_callcenter());
drop policy if exists "prospecto contactos callcenter" on prospecto_contactos;
create policy "prospecto contactos callcenter" on prospecto_contactos for select using (
  es_titular() and exists (select 1 from prospectos p where p.id = prospecto_id and p.callcenter_id is not null and p.callcenter_id = mi_callcenter()));

drop policy if exists "movimientos lee" on callcenter_movimientos;
create policy "movimientos lee" on callcenter_movimientos for select using (es_admin() or (es_titular() and callcenter_id = mi_callcenter()));
grant select on callcenter_movimientos to authenticated;

drop policy if exists "consultas lee" on prospecto_consultas;
create policy "consultas lee" on prospecto_consultas for select using (es_admin() or es_de_mi_equipo(operador_id));
grant select on prospecto_consultas to authenticated;

drop policy if exists "evaluaciones lee" on llamada_evaluaciones;
create policy "evaluaciones lee" on llamada_evaluaciones for select using (
  es_admin() or operador_id = mi_operador() or es_de_mi_equipo(operador_id));
grant select on llamada_evaluaciones to authenticated;

drop policy if exists "metas lee" on callcenter_metas;
create policy "metas lee" on callcenter_metas for select using (es_admin() or operador_id = mi_operador() or es_de_mi_equipo(operador_id));
grant select on callcenter_metas to authenticated;

-- Comisiones: el agente de un callcenter no ve montos; el titular ve los de su equipo.
drop policy if exists "comisiones lee" on comisiones;
create policy "comisiones lee" on comisiones for select using (
  es_admin() or (operador_id = mi_operador() and not es_agente_callcenter()) or es_de_mi_equipo(operador_id));
drop policy if exists "ajustes comision lee" on comision_ajustes;
create policy "ajustes comision lee" on comision_ajustes for select using (
  es_admin() or (operador_id = mi_operador() and not es_agente_callcenter()) or es_de_mi_equipo(operador_id));

-- Privacidad: membresías y regalos solo de quien los tiene (y administración).
drop policy if exists "membresia propia" on membresias;
create policy "membresia propia" on membresias for select using (usuario_id = auth.uid() or es_admin());
drop policy if exists "regalo propio" on regalos;
create policy "regalo propio" on regalos for select using (comprador_id = auth.uid() or es_admin());

-- 4. Asignación ---------------------------------------------------------------
-- El callcenter del prospecto sigue a su operador; el operador no cambia nada de esto.
create or replace function prospecto_proteger() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if es_admin() or auth.uid() is null or current_setting('mara.llamada', true) = '1' or current_setting('mara.callcenter', true) = '1' then
    if new.asignado_a is distinct from old.asignado_a then
      new.asignado_en := case when new.asignado_a is null then null else now() end;
      if new.asignado_a is not null then
        new.callcenter_id := (select callcenter_id from operadores where id = new.asignado_a);
      end if;
    end if;
    if new.callcenter_id is distinct from old.callcenter_id then
      new.callcenter_en := case when new.callcenter_id is null then null else now() end;
    end if;
    return new;
  end if;
  new.asignado_a := old.asignado_a; new.asignado_en := old.asignado_en; new.token := old.token;
  new.callcenter_id := old.callcenter_id; new.callcenter_en := old.callcenter_en;
  new.llamadas_intentos := old.llamadas_intentos; new.llamada_toque := old.llamada_toque;
  new.ultima_llamada := old.ultima_llamada; new.ultimo_resultado := old.ultimo_resultado;
  return new;
end; $$;

-- Movimiento de la empresa ligada y sus planes vigentes al operador nuevo
-- (misma regla del 20/10: las comisiones que vengan son de quien la atiende ahora).
create or replace function prospectos_mover_empresas(p_ids uuid[], p_operador uuid) returns void
language plpgsql security definer set search_path = public as $$
begin
  if p_operador is null then return; end if;
  update empresas e set operador_id = p_operador
   where e.id in (select empresa_id from prospectos where id = any(p_ids) and empresa_id is not null)
     and e.operador_id is distinct from p_operador;
  update empresas_planes pl set operador_id = p_operador
   where pl.empresa_id in (select empresa_id from prospectos where id = any(p_ids) and empresa_id is not null)
     and pl.estado not in ('cancelado','vencido','rechazado')
     and pl.operador_id is distinct from p_operador;
end; $$;
revoke all on function prospectos_mover_empresas(uuid[], uuid) from public, anon, authenticated;

-- Administración asigna a un operador (interno o de callcenter) o recupera (null).
create or replace function asignar_prospectos(p_ids uuid[], p_operador uuid)
returns int
language plpgsql security definer set search_path = public as $$
declare n int; cc uuid;
begin
  if not es_admin() then raise exception 'Solo administración asigna prospectos.'; end if;
  if p_operador is not null and not exists (select 1 from operadores where id = p_operador and activo) then
    raise exception 'Ese operador no existe o está inactivo.';
  end if;
  if p_operador is not null then
    select o.callcenter_id into cc from operadores o where o.id = p_operador;
    if cc is not null and not exists (select 1 from callcenters where id = cc and activo) then raise exception 'Ese callcenter está inactivo.'; end if;
    update prospectos set asignado_a = p_operador where id = any(p_ids);
  else
    -- Recuperar: deja de estar en cualquier consola y en cualquier callcenter.
    insert into callcenter_movimientos (prospecto_id, callcenter_id, accion)
      select id, callcenter_id, 'recuperado' from prospectos where id = any(p_ids) and callcenter_id is not null;
    update prospectos set asignado_a = null, callcenter_id = null where id = any(p_ids);
  end if;
  get diagnostics n = row_count;
  if p_operador is not null then
    insert into callcenter_movimientos (prospecto_id, callcenter_id, operador_id, accion)
      select id, cc, p_operador, case when cc is null then 'a_operador' else 'repartido' end from prospectos where id = any(p_ids);
    perform prospectos_mover_empresas(p_ids, p_operador);
  end if;
  return n;
end; $$;
revoke all on function asignar_prospectos(uuid[], uuid) from public, anon;
grant execute on function asignar_prospectos(uuid[], uuid) to authenticated;

-- Administración manda un lote a la bolsa de un callcenter (lo reparte su titular).
create or replace function asignar_a_callcenter(p_ids uuid[], p_callcenter uuid)
returns int
language plpgsql security definer set search_path = public as $$
declare n int;
begin
  if not es_admin() then raise exception 'Solo administración asigna prospectos.'; end if;
  if not exists (select 1 from callcenters where id = p_callcenter and activo) then raise exception 'Ese callcenter no existe o está inactivo.'; end if;
  with movidos as (
    update prospectos set asignado_a = null, callcenter_id = p_callcenter
     where id = any(p_ids) and callcenter_id is distinct from p_callcenter
    returning id)
  insert into callcenter_movimientos (prospecto_id, callcenter_id, accion)
    select id, p_callcenter, 'al_callcenter' from movidos;
  get diagnostics n = row_count;
  return n;
end; $$;
revoke all on function asignar_a_callcenter(uuid[], uuid) from public, anon;
grant execute on function asignar_a_callcenter(uuid[], uuid) to authenticated;

-- El titular reparte (o regresa a su bolsa con null) prospectos de su callcenter.
create or replace function callcenter_repartir(p_ids uuid[], p_operador uuid)
returns int
language plpgsql security definer set search_path = public as $$
declare cc uuid := mi_callcenter(); n int;
begin
  if not es_titular() then raise exception 'Solo el titular del callcenter reparte prospectos.'; end if;
  if exists (select 1 from prospectos where id = any(p_ids) and callcenter_id is distinct from cc) then
    raise exception 'Algunos prospectos ya no son de tu callcenter. Actualiza la pantalla.';
  end if;
  if p_operador is not null and not exists (select 1 from operadores where id = p_operador and callcenter_id = cc and activo) then
    raise exception 'Ese agente no es de tu equipo o está inactivo.';
  end if;
  perform set_config('mara.callcenter', '1', true);
  update prospectos set asignado_a = p_operador where id = any(p_ids) and asignado_a is distinct from p_operador;
  get diagnostics n = row_count;
  perform set_config('mara.callcenter', '', true);
  insert into callcenter_movimientos (prospecto_id, callcenter_id, operador_id, accion)
    select id, cc, p_operador, case when p_operador is null then 'a_bolsa' else 'repartido' end from prospectos where id = any(p_ids);
  perform prospectos_mover_empresas(p_ids, p_operador);
  return n;
end; $$;
revoke all on function callcenter_repartir(uuid[], uuid) from public, anon;
grant execute on function callcenter_repartir(uuid[], uuid) to authenticated;

-- Reparto parejo: los de la bolsa (o los elegidos) van primero a quien tiene menos abiertos.
create or replace function callcenter_repartir_parejo(p_ids uuid[] default null, p_incluir_titular boolean default false)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  cc uuid := mi_callcenter(); ags uuid[]; cargas int[]; i int; k int; menor int; pid uuid; total int := 0; salida jsonb := '{}'::jsonb;
begin
  if not es_titular() then raise exception 'Solo el titular del callcenter reparte prospectos.'; end if;
  select array_agg(o.id order by o.nombre),
         array_agg((select count(*)::int from prospectos p where p.asignado_a = o.id
                     and p.estado not in ('no_interesa','descartado','baja','cliente')) order by o.nombre)
    into ags, cargas
    from operadores o where o.callcenter_id = cc and o.activo and (p_incluir_titular or not o.es_titular);
  if ags is null then raise exception 'No tienes agentes activos para repartir.'; end if;
  perform set_config('mara.callcenter', '1', true);
  for pid in select p.id from prospectos p
              where p.callcenter_id = cc and p.asignado_a is null
                and p.estado not in ('no_interesa','descartado','baja','cliente')
                and (p_ids is null or p.id = any(p_ids))
              order by p.num_origen nulls last, p.creado_en
  loop
    k := 1; menor := cargas[1];
    for i in 2 .. array_length(ags, 1) loop
      if cargas[i] < menor then k := i; menor := cargas[i]; end if;
    end loop;
    update prospectos set asignado_a = ags[k] where id = pid;
    insert into callcenter_movimientos (prospecto_id, callcenter_id, operador_id, accion, nota) values (pid, cc, ags[k], 'repartido', 'Reparto parejo');
    perform prospectos_mover_empresas(array[pid], ags[k]);
    cargas[k] := cargas[k] + 1; total := total + 1;
    salida := jsonb_set(salida, array[ags[k]::text], to_jsonb(coalesce((salida->>(ags[k]::text))::int, 0) + 1));
  end loop;
  perform set_config('mara.callcenter', '', true);
  return jsonb_build_object('repartidos', total, 'por_agente', salida);
end; $$;
revoke all on function callcenter_repartir_parejo(uuid[], boolean) from public, anon;
grant execute on function callcenter_repartir_parejo(uuid[], boolean) to authenticated;

-- 15 días sin ningún intento (y sin llamada agendada a futuro): regresa a administración.
create or replace function callcenter_caducar() returns int
language plpgsql security definer set search_path = public as $$
declare dias int := coalesce((select callcenter_dias_caducidad from ajustes limit 1), 15); n int; limite timestamptz;
begin
  if auth.uid() is not null and not es_admin() then raise exception 'Solo administración.'; end if;
  limite := now() - make_interval(days => dias);
  create temp table if not exists _caducan (id uuid, callcenter_id uuid, operador_id uuid) on commit drop;
  delete from _caducan;
  insert into _caducan
    select p.id, p.callcenter_id, p.asignado_a from prospectos p
     where p.callcenter_id is not null
       and p.estado not in ('no_interesa','descartado','baja','cliente')
       and greatest(p.callcenter_en, coalesce(p.ultima_llamada, p.callcenter_en)) < limite
       and (p.proxima_llamada is null or p.proxima_llamada < limite);
  insert into callcenter_movimientos (prospecto_id, callcenter_id, operador_id, accion, nota, por)
    select id, callcenter_id, operador_id, 'regresado', dias || ' días sin gestión', null from _caducan;
  update prospectos set asignado_a = null, callcenter_id = null where id in (select id from _caducan);
  get diagnostics n = row_count;
  return n;
end; $$;
revoke all on function callcenter_caducar() from public, anon;
grant execute on function callcenter_caducar() to authenticated, service_role;

-- Diario a las 7:00 a. m. del centro de México (13:00 UTC).
select cron.unschedule('mara-callcenter-caducar') where exists (select 1 from cron.job where jobname = 'mara-callcenter-caducar');
select cron.schedule('mara-callcenter-caducar', '0 13 * * *', $$ select callcenter_caducar() $$);

-- Las solicitudes de prueba del sitio van a operadores internos (o se quedan en su callcenter).
create or replace function operador_menos_cargado() returns uuid
language sql stable security definer set search_path = public as $$
  select o.id from operadores o
  where o.activo and o.usuario_id is not null and o.callcenter_id is null
  order by (select count(*) from prospectos p where p.asignado_a = o.id
              and p.estado not in ('no_interesa','descartado','baja','cliente')
              and (p.proxima_llamada is null or p.proxima_llamada < now() + interval '1 day')), random()
  limit 1;
$$;

create or replace function prospecto_solicitud(p_empresa text, p_nombre text, p_puesto text, p_correo text, p_telefono text, p_personas integer default null, p_mensaje text default null)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  p prospectos; c text := lower(btrim(coalesce(p_correo, ''))); t text := right(regexp_replace(coalesce(p_telefono, ''), '\D', '', 'g'), 10);
  op uuid; nuevo boolean := false; resumen text;
begin
  if length(btrim(coalesce(p_empresa, ''))) < 2 then raise exception 'Escribe el nombre de la empresa.'; end if;
  if length(btrim(coalesce(p_nombre, ''))) < 2 then raise exception 'Escribe tu nombre.'; end if;
  if c !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then raise exception 'Revisa tu correo.'; end if;
  if length(t) <> 10 then raise exception 'Escribe un teléfono de 10 dígitos.'; end if;
  select * into p from prospectos
   where lower(coalesce(contacto_correo, '')) = c or position(c in lower(coalesce(correo, ''))) > 0
      or right(regexp_replace(coalesce(telefono, ''), '\D', '', 'g'), 10) = t
      or right(regexp_replace(coalesce(whatsapp, ''), '\D', '', 'g'), 10) = t
   order by (asignado_a is not null) desc, creado_en limit 1;
  -- La misma solicitud dos veces en 10 minutos no se duplica.
  if p.id is not null and (p.extra->>'solicitud_en') is not null and (p.extra->>'solicitud_en')::timestamptz > now() - interval '10 minutes' then
    return jsonb_build_object('ok', true, 'id', p.id, 'repetida', true);
  end if;
  if p.id is null then
    insert into prospectos (nombre, nombre_corto, telefono, correo, estado, lote)
      values (btrim(p_empresa), btrim(p_empresa), t, c, 'respondio', 'Sitio web')
      returning * into p;
    nuevo := true;
  end if;
  -- Su operador si está activo; si está en la bolsa de un callcenter, a su titular; si no, al interno menos cargado.
  op := case when p.asignado_a is not null and exists (select 1 from operadores where id = p.asignado_a and activo) then p.asignado_a
             when p.callcenter_id is not null then (select o.id from operadores o join callcenters k on k.id = o.callcenter_id
                                                     where o.callcenter_id = p.callcenter_id and o.es_titular and o.activo and k.activo)
             else null end;
  if op is null then op := operador_menos_cargado(); end if;
  resumen := 'Pidió la prueba sin costo desde el sitio' || coalesce(' · ' || p_personas || ' personas', '') ||
             coalesce(' · «' || nullif(btrim(coalesce(p_mensaje, '')), '') || '»', '');
  update prospectos set
    estado = case when estado in ('nuevo','contactado','no_interesa','descartado') then 'respondio' else estado end,
    asignado_a = op,
    proxima_llamada = now(),
    contacto_nombre = btrim(p_nombre), contacto_puesto = nullif(btrim(coalesce(p_puesto, '')), ''), contacto_correo = c,
    telefono = coalesce(nullif(telefono, ''), t),
    extra = extra || jsonb_build_object('origen', 'sitio', 'solicitud_en', now(), 'personas', p_personas, 'mensaje', nullif(btrim(coalesce(p_mensaje, '')), '')),
    actualizado_en = now()
   where id = p.id returning * into p;
  insert into prospecto_contactos (prospecto_id, canal, sentido, resumen, resultado, contacto_nombre, contacto_puesto)
    values (p.id, 'otro', 'entrante', resumen, 'Pidió prueba desde el sitio', btrim(p_nombre), nullif(btrim(coalesce(p_puesto, '')), ''));
  return jsonb_build_object('ok', true, 'id', p.id, 'nuevo', nuevo, 'operador_id', op);
end; $$;

