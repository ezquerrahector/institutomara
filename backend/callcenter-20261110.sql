  update callcenters set activo = p_activo where id = p_callcenter;
  if not found then raise exception 'Callcenter no encontrado.'; end if;
  if not p_activo then
    update operadores set activo = false where callcenter_id = p_callcenter and activo;
    insert into callcenter_movimientos (prospecto_id, callcenter_id, operador_id, accion, nota)
