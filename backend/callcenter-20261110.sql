returns operadores
language plpgsql security definer set search_path = public as $$
declare
  cc uuid := mi_callcenter(); limpio text := lower(btrim(coalesce(p_correo, ''))); fila operadores; o operadores;
  tope numeric := coalesce((select plan_desc_max_operador from ajustes limit 1), 10);
