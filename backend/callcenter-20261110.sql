-- Administración activa o desactiva un callcenter. Al desactivarlo, su gente
-- queda sin acceso y todos sus prospectos regresan a administración.
create or replace function callcenter_estado(p_callcenter uuid, p_activo boolean)
returns int
language plpgsql security definer set search_path = public as $$
declare n int := 0;
begin
