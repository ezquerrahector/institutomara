  ini_mes timestamptz := (date_trunc('month', hoy)::timestamp at time zone 'America/Mexico_City');
  yo uuid := mi_operador();
  -- El agente de un callcenter no ve montos de comisión (se los paga su callcenter).
  ver_com boolean := es_admin() or auth.uid() is null or not es_agente_callcenter();
  -- equipo_metricas() pide las cifras de todo el equipo del titular.
  equipo boolean := current_setting('mara.equipo', true) = '1' and es_titular();
begin
  if not es_admin() and yo is null and auth.uid() is not null then raise exception 'Solo administración y operadores.'; end if;
  return query
  with ops as (
    select o.* from operadores o
    where (es_admin() or auth.uid() is null or o.id = yo or (equipo and o.callcenter_id = mi_callcenter()))
      and (p_operador is null or o.id = p_operador)
  ),
  pros as (
    select pr.*, (pr.estado in ('no_interesa','descartado','baja','cliente')) as cerrado from prospectos pr where pr.asignado_a in (select id from ops)
  ),
  ll as (
    select o.id as op, c.* from prospecto_contactos c join ops o on o.usuario_id = c.creado_por
    where c.canal = 'llamada' and c.fecha >= least(ini_mes, ini_sem)
  )
  select o.id, o.nombre, o.activo,
    (select count(*)::int from pros where asignado_a = o.id and not cerrado and proxima_llamada >= ini_hoy and proxima_llamada < fin_hoy),
    (select count(*)::int from pros where asignado_a = o.id and not cerrado and coalesce(llamadas_intentos, 0) = 0 and proxima_llamada is null),
    (select count(*)::int from pros where asignado_a = o.id and not cerrado and proxima_llamada < ini_hoy),
    (select count(*)::int from pros where asignado_a = o.id),
    (select count(*)::int from ll where op = o.id and fecha >= ini_hoy),
    (select count(*)::int from ll where op = o.id and fecha >= ini_sem),
    (select count(*)::int from ll where op = o.id and fecha >= ini_mes),
    (select count(*)::int from ll where op = o.id and fecha >= ini_mes and toque is not null),
    coalesce((select jsonb_object_agg(r, n) from (select coalesce(resultado, '—') r, count(*) n from ll where op = o.id and fecha >= ini_hoy group by 1) x), '{}'::jsonb),
    coalesce((select jsonb_object_agg(r, n) from (select coalesce(resultado, '—') r, count(*) n from ll where op = o.id and fecha >= ini_mes group by 1) x), '{}'::jsonb),
    ((select count(*)::int from empresas_planes p where p.operador_id = o.id and p.estado = 'prueba' and p.creado_en >= ini_mes)
      + (select count(*)::int from empresas_compras k join empresas e on e.id = k.empresa_id where e.operador_id = o.id and k.medio = 'piloto' and k.creado_en >= ini_mes)),
    (select count(*)::int from empresas_planes p where p.operador_id = o.id and p.estado = 'prueba' and p.convertida_en is null and p.vigente_hasta >= now()),
    (select count(*)::int from empresas_planes p where p.operador_id = o.id and p.estado <> 'prueba' and p.inicio >= ini_mes),
    (select count(*)::int from empresas_planes p where p.operador_id = o.id and p.estado = 'activo' and p.vigente_hasta >= now()),
    case when ver_com then coalesce((select sum(c.monto) from comisiones c where c.operador_id = o.id and c.creado_en >= ini_mes and c.cancelada_en is null), 0) else 0 end,
    case when not ver_com then 0 else coalesce((select sum(c.monto) from comisiones c where c.operador_id = o.id and c.cancelada_en is null and (c.corte_id is null
               or exists (select 1 from comision_cortes k where k.id = c.corte_id and k.estado <> 'pagado'))), 0)
      + coalesce((select sum(a.monto) from comision_ajustes a where a.operador_id = o.id and (a.corte_id is null
               or exists (select 1 from comision_cortes k where k.id = a.corte_id and k.estado <> 'pagado'))), 0) end,
    greatest((select max(fecha) from prospecto_contactos c where c.creado_por = o.usuario_id),
             (select ultimo_acceso from perfiles where id = o.usuario_id)),
    coalesce((select jsonb_agg(jsonb_build_object('id', a.id, 'nombre', coalesce(a.nombre_corto, a.nombre), 'proxima', a.proxima_llamada,
                     'estado', a.estado, 'resultado', a.ultimo_resultado, 'toque', a.llamada_toque, 'telefono', a.telefono,
                     'comentario', (select c.resumen from prospecto_contactos c where c.prospecto_id = a.id and c.canal = 'llamada' order by c.fecha desc limit 1))
                     order by a.proxima_llamada)
              from (select * from pros where asignado_a = o.id and not cerrado and proxima_llamada < ini_hoy order by proxima_llamada limit 50) a), '[]'::jsonb)
  from ops o
  order by o.activo desc, o.nombre;
end; $$;
revoke all on function operador_metricas(uuid) from public, anon;
grant execute on function operador_metricas(uuid) to authenticated, service_role;

-- Cifras de todo el equipo del titular (misma forma que operador_metricas).
create or replace function equipo_metricas()
returns setof jsonb
language plpgsql security definer set search_path = public as $$
begin
  if not es_titular() then raise exception 'Solo el titular del callcenter.'; end if;
  perform set_config('mara.equipo', '1', true);
  return query select to_jsonb(m) from operador_metricas(null) m;
  perform set_config('mara.equipo', '', true);
end; $$;
revoke all on function equipo_metricas() from public, anon;
grant execute on function equipo_metricas() to authenticated;

-- 11. Registro de llamada con liga de grabación opcional -----------------------------
drop function if exists registrar_llamada(uuid, text, text, text, text, text, timestamptz);
create or replace function registrar_llamada(p_prospecto uuid, p_resultado text, p_contacto_nombre text default null,
                                             p_contacto_puesto text default null, p_contacto_correo text default null,
                                             p_comentario text default null, p_proxima timestamptz default null,
                                             p_grabacion text default null)
returns prospectos
language plpgsql security definer set search_path = public as $$
declare
  p prospectos; fila prospectos; efectiva boolean; toque int; prox timestamptz; est text;
  correo_limpio text := nullif(lower(btrim(coalesce(p_contacto_correo,''))), '');
begin
  select * into p from prospectos where id = p_prospecto for update;
  if p.id is null then raise exception 'Prospecto no encontrado.'; end if;
  if not (es_admin() or (p.asignado_a is not null and p.asignado_a = mi_operador())) then
    raise exception 'Este prospecto no está asignado a ti.';
  end if;
  if p_resultado not in ('no_contesto','buzon','equivocado','recepcion','otro_dia','info_correo','piloto','demo','proveedor','no_interesa') then
    raise exception 'Elige el resultado de la llamada.';
  end if;
  if correo_limpio is not null and correo_limpio !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then raise exception 'Revisa el correo.'; end if;
  if p_resultado = 'info_correo' and coalesce(correo_limpio, p.contacto_correo) is null then
    raise exception 'Escribe el correo al que pidió la información.';
  end if;
  if p_resultado in ('otro_dia','demo') and p_proxima is null then
    raise exception 'Escribe la fecha y hora en que hay que volver a llamar.';
  end if;

  -- Cuenta como «conversación» cuando se habló con quien decide.
  efectiva := p_resultado in ('otro_dia','info_correo','piloto','demo','proveedor','no_interesa');
  toque := p.llamada_toque + case when efectiva then 1 else 0 end;

  prox := coalesce(p_proxima, case p_resultado
    when 'no_contesto' then dia_habil(1)
    when 'buzon' then dia_habil(2)
    when 'recepcion' then dia_habil(2)
    when 'info_correo' then dia_habil(3)
    when 'piloto' then dia_habil(7)       -- revisar cómo va la prueba
    when 'proveedor' then dia_habil(40)   -- volver a ofrecer en unos dos meses
    else null end);
  if p_resultado in ('equivocado','no_interesa') then prox := null; end if;
  -- Tres conversaciones sin decisión: se deja descansar tres meses.
  if efectiva and toque >= 3 and p_resultado in ('info_correo','otro_dia','proveedor') and p_proxima is null then prox := dia_habil(60); end if;

  est := case p_resultado
    when 'equivocado' then 'descartado'
    when 'no_interesa' then 'no_interesa'
    when 'piloto' then 'piloto'
    when 'demo' then 'demo'
    when 'info_correo' then case when p.estado in ('nuevo','contactado') then 'respondio' else p.estado end
    when 'otro_dia' then case when p.estado in ('nuevo','contactado') then 'respondio' else p.estado end
    else case when p.estado = 'nuevo' then 'contactado' else p.estado end end;

  insert into prospecto_contactos (prospecto_id, canal, sentido, toque, resumen, resultado, creado_por, contacto_nombre, contacto_puesto, grabacion)
    values (p.id, 'llamada', 'saliente', case when efectiva then toque else null end,
            nullif(btrim(coalesce(p_comentario,'')), ''), llamada_resultado_texto(p_resultado), auth.uid(),
            nullif(btrim(coalesce(p_contacto_nombre,'')), ''), nullif(btrim(coalesce(p_contacto_puesto,'')), ''),
            nullif(left(btrim(coalesce(p_grabacion,'')), 500), ''));

  -- Permiso de esta transacción para los campos que protege prospecto_proteger().
  perform set_config('mara.llamada', '1', true);
  update prospectos set
    estado = est,
    secuencia = case when est in ('respondio','demo','piloto','no_interesa','descartado') then false else secuencia end,
    llamadas_intentos = llamadas_intentos + 1,
    llamada_toque = toque,
    ultima_llamada = now(),
    ultimo_resultado = p_resultado,
    proxima_llamada = prox,
    contacto_nombre = coalesce(nullif(btrim(coalesce(p_contacto_nombre,'')), ''), contacto_nombre),
    contacto_puesto = coalesce(nullif(btrim(coalesce(p_contacto_puesto,'')), ''), contacto_puesto),
    contacto_correo = coalesce(correo_limpio, contacto_correo),
    -- Quien pidió información por correo queda marcado hasta que se le envíe.
    extra = case when p_resultado = 'info_correo' then coalesce(extra, '{}'::jsonb) || jsonb_build_object('info_pendiente', true) else extra end
  where id = p.id
  returning * into fila;
  perform set_config('mara.llamada', '', true);
  return fila;
end; $$;
revoke all on function registrar_llamada(uuid, text, text, text, text, text, timestamptz, text) from public, anon;
grant execute on function registrar_llamada(uuid, text, text, text, text, text, timestamptz, text) to authenticated;

notify pgrst, 'reload schema';
select 'ok' as resultado;
