-- 5. Administración responde (con o sin ajuste) y paga ------------------------------
create or replace function corte_responder(p_corte uuid, p_respuesta text, p_ajuste numeric default null, p_motivo text default null)
returns comision_cortes
language plpgsql security definer set search_path = public as $$
declare k comision_cortes;
begin
  if not es_admin() then raise exception 'Solo administración.'; end if;
  select * into k from comision_cortes where id = p_corte for update;
  if k.id is null then raise exception 'Recibo no encontrado.'; end if;
  if k.estado = 'pagado' then raise exception 'Este recibo ya está pagado; el ajuste va en el siguiente corte.'; end if;
  if coalesce(p_ajuste, 0) <> 0 then
    if length(btrim(coalesce(p_motivo, ''))) < 3 then raise exception 'Escribe el motivo del ajuste (lo verá el operador).'; end if;
    insert into comision_ajustes (operador_id, corte_id, tipo, monto, motivo, creado_por)
      values (k.operador_id, k.id, 'manual', round(p_ajuste, 2), btrim(p_motivo), auth.uid());
    k := corte_recalcular(k.id);
    if k.total < 0 then raise exception 'El total del recibo no puede quedar negativo.'; end if;
  elsif length(btrim(coalesce(p_respuesta, ''))) < 3 then
    raise exception 'Escribe la respuesta para el operador.';
  end if;
  update comision_cortes set estado = 'enviado', aceptado_en = null, respuesta = nullif(btrim(coalesce(p_respuesta, '')), ''),
         respuesta_en = now(), enviado_en = now()
   where id = k.id returning * into k;
  return k;
end; $$;
revoke all on function corte_responder(uuid, text, numeric, text) from public, anon;
grant execute on function corte_responder(uuid, text, numeric, text) to authenticated;

create or replace function corte_pagar(p_corte uuid, p_referencia text, p_nombre text, p_tipo text, p_datos text)
returns comision_cortes
language plpgsql security definer set search_path = public as $$
declare k comision_cortes;
begin
  if not es_admin() then raise exception 'Solo administración.'; end if;
  select * into k from comision_cortes where id = p_corte for update;
  if k.id is null then raise exception 'Recibo no encontrado.'; end if;
  if k.estado = 'pagado' then raise exception 'Este recibo ya está marcado como pagado.'; end if;
  if k.estado <> 'aceptado' then raise exception 'El operador todavía no acepta este recibo.'; end if;
  if length(btrim(coalesce(p_referencia, ''))) < 3 then raise exception 'Escribe la referencia o clave de rastreo de la transferencia.'; end if;
  if coalesce(p_tipo, '') not in ('application/pdf','image/png','image/jpeg','image/webp') then
    raise exception 'Sube el comprobante en PDF o imagen (PNG o JPG).'; end if;
  if length(coalesce(p_datos, '')) < 100 then raise exception 'Sube el comprobante de la transferencia.'; end if;
  if length(p_datos) > 5600000 then raise exception 'El comprobante pesa más de 4 MB. Sube uno más ligero.'; end if;
  insert into comision_comprobantes (corte_id, nombre, tipo, datos, subido_por)
    values (k.id, left(coalesce(nullif(btrim(p_nombre), ''), 'comprobante'), 120), p_tipo, p_datos, auth.uid())
    on conflict (corte_id) do update set nombre = excluded.nombre, tipo = excluded.tipo, datos = excluded.datos,
      subido_por = excluded.subido_por, creado_en = now();
  update comision_cortes set estado = 'pagado', pagado_en = now(), referencia = btrim(p_referencia), pagado_por = auth.uid()
   where id = k.id returning * into k;
  return k;
end; $$;
revoke all on function corte_pagar(uuid, text, text, text, text) from public, anon;
grant execute on function corte_pagar(uuid, text, text, text, text) to authenticated;

-- 6. Reembolsos y contracargos (lo llama el servidor con el aviso de Mercado Pago) ---
create or replace function plan_pago_reembolso(p_pago text, p_reembolsado numeric, p_motivo text default 'reembolso')
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  pp plan_pagos; c comisiones; k comision_cortes; p empresas_planes; e empresas;
  total numeric; delta numeric; rev numeric; completo boolean; accion text := 'sin_comision';
  etiqueta text := case when p_motivo = 'contracargo' then 'contracargo' else 'reembolso' end;
begin
  select * into pp from plan_pagos where mp_pago_id = p_pago for update;
  if pp.id is null then return jsonb_build_object('ok', false, 'motivo', 'no es pago de plan'); end if;
  total := least(greatest(coalesce(p_reembolsado, 0), 0), pp.monto);
  delta := round(total - pp.reembolsado, 2);
  if delta <= 0 then return jsonb_build_object('ok', true, 'motivo', 'sin cambios'); end if;
  completo := total >= pp.monto - 0.009;
  update plan_pagos set reembolsado = total, reembolso_en = now() where id = pp.id;
  select * into p from empresas_planes where id = pp.plan_id;
  select * into e from empresas where id = p.empresa_id;
  insert into pagos (usuario_id, curso_id, monto, medio, referencia_mp, nota)
    values (null, null, -delta, 'Mercado Pago', p_pago || '-' || etiqueta || '-' || to_char(now(), 'YYYYMMDDHH24MISS'),
            'REVISAR ' || etiqueta || ' del plan de ' || coalesce(e.nombre, '—') || ' (pago ' || pp.numero || '): ' || delta)
    on conflict (referencia_mp) do nothing;

  select * into c from comisiones where plan_pago_id = pp.id for update;
  if c.id is not null and c.cancelada_en is null then
    rev := case when completo then c.monto else least(c.monto, round(coalesce(c.monto_original, c.monto) * delta / pp.monto, 2)) end;
    if c.corte_id is not null then select * into k from comision_cortes where id = c.corte_id for update; end if;
    if c.corte_id is null or k.estado <> 'pagado' then
      -- Aún no se paga: la comisión se reduce o se cancela.
      update comisiones set monto_original = coalesce(monto_original, monto), monto = round(monto - rev, 2),
             cancelada_en = case when completo then now() else cancelada_en end,
             nota = 'Ajustada por ' || etiqueta || ' de ' || to_char(now() at time zone 'America/Mexico_City', 'DD/MM/YYYY')
       where id = c.id;
      accion := 'cancelada';
      if c.corte_id is not null then
        perform corte_recalcular(k.id);
        if k.estado in ('aceptado','en_revision','enviado') then
          update comision_cortes set estado = 'enviado', aceptado_en = null, enviado_en = now(),
                 respuesta = 'Se ajustó porque ' || coalesce(e.nombre, 'una empresa') || ' tuvo un ' || etiqueta || '. Revisa el recibo y acéptalo de nuevo.',
                 respuesta_en = now()
           where id = k.id;
        end if;
        accion := 'cancelada_en_recibo';
      end if;
    else
      -- Ya se pagó: se descuenta del siguiente corte.
      insert into comision_ajustes (operador_id, comision_id, tipo, monto, motivo)
        values (c.operador_id, c.id, 'reembolso', -rev,
                'Ajuste por ' || etiqueta || ': ' || coalesce(e.nombre, '—') || ', pago ' || pp.numero || ' (recibo ' || k.folio || ')');
      accion := 'ajuste_siguiente';
    end if;
  end if;
  return jsonb_build_object('ok', true, 'accion', accion, 'empresa', e.nombre, 'plan_id', p.id, 'completo', completo,
                            'monto', delta, 'operador_id', c.operador_id, 'corte_id', c.corte_id, 'comision', rev);
end; $$;
revoke all on function plan_pago_reembolso(text, numeric, text) from public, anon, authenticated;
grant execute on function plan_pago_reembolso(text, numeric, text) to service_role;

