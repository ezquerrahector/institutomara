-- CLABE de 18 dígitos con su dígito verificador (pesos 3,7,1).
create or replace function clabe_valida(p text) returns boolean
language plpgsql immutable as $$
declare s int := 0; i int; w int[] := array[3,7,1];
begin
  if p is null or p !~ '^[0-9]{18}$' then return false; end if;
  for i in 1..17 loop
    s := s + ((substr(p, i, 1)::int * w[((i - 1) % 3) + 1]) % 10);
  end loop;
  return ((10 - (s % 10)) % 10) = substr(p, 18, 1)::int;
end; $$;
grant execute on function clabe_valida(text) to anon, authenticated;

-- El operador guarda (o cambia) su cuenta. Solo él; administración la ve.
create or replace function operador_datos_bancarios(p_titular text, p_banco text, p_clabe text)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare o operadores; c text := regexp_replace(coalesce(p_clabe, ''), '\D', '', 'g'); cambio boolean;
begin
  select * into o from operadores where id = mi_operador();
  if o.id is null then raise exception 'Solo los operadores capturan su cuenta para comisiones.'; end if;
  if nullif(btrim(coalesce(p_titular, '')), '') is null then raise exception 'Escribe el nombre del titular de la cuenta.'; end if;
  if nullif(btrim(coalesce(p_banco, '')), '') is null then raise exception 'Escribe el banco.'; end if;
  if not clabe_valida(c) then raise exception 'La CLABE debe tener 18 dígitos y ser válida. Revísala en tu app del banco.'; end if;
  cambio := o.clabe is not null and (o.clabe <> c or coalesce(o.banco, '') <> btrim(p_banco) or coalesce(o.titular, '') <> btrim(p_titular));
  update operadores set titular = btrim(p_titular), banco = btrim(p_banco), clabe = c, banco_actualizado_en = now(),
         banco_cambio_visto = case when o.clabe is null then true when cambio then false else banco_cambio_visto end
   where id = o.id;
  return jsonb_build_object('ok', true, 'cambio', cambio, 'primera_vez', o.clabe is null);
end; $$;
revoke all on function operador_datos_bancarios(text, text, text) from public, anon;
grant execute on function operador_datos_bancarios(text, text, text) to authenticated;

