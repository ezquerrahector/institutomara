-- 3. Cálculo y armado de cortes -----------------------------------------------------
create or replace function corte_recalcular(p_corte uuid) returns comision_cortes
language plpgsql security definer set search_path = public as $$
declare k comision_cortes; s numeric; a numeric;
begin
  select coalesce(sum(monto), 0) into s from comisiones where corte_id = p_corte;
  select coalesce(sum(monto), 0) into a from comision_ajustes where corte_id = p_corte;
  update comision_cortes set subtotal = round(s, 2), ajustes = round(a, 2), total = round(s + a, 2) where id = p_corte returning * into k;
  return k;
end; $$;
revoke all on function corte_recalcular(uuid) from public, anon, authenticated;

-- Último cierre (15 o fin de mes) ANTERIOR a hoy, en hora de la Ciudad de México.
create or replace function corte_ultimo_cierre(p_hoy date default null) returns date
language sql stable as $$
  with h as (select coalesce(p_hoy, (now() at time zone 'America/Mexico_City')::date) as d)
  select case when extract(day from d) > 15 then date_trunc('month', d)::date + 14
              else (date_trunc('month', d) - interval '1 day')::date end
  from h;
$$;

-- Arma los cortes que falten hasta p_hasta (por omisión, el último cierre). Lo llama la tarea diaria.
create or replace function comisiones_generar_cortes(p_hasta date default null) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  hasta date := coalesce(p_hasta, corte_ultimo_cierre());
  limite timestamptz := ((hasta + 1)::timestamp at time zone 'America/Mexico_City');
  o operadores; k comision_cortes; previo date; s numeric; a numeric; desde date; salida jsonb := '[]'::jsonb;
begin
  if auth.uid() is not null and not es_admin() then raise exception 'Solo administración.'; end if;
  for o in select * from operadores order by nombre loop
    select coalesce(sum(monto), 0) into s from comisiones
      where operador_id = o.id and corte_id is null and cancelada_en is null and creado_en < limite and monto <> 0;
    select coalesce(sum(monto), 0) into a from comision_ajustes
      where operador_id = o.id and corte_id is null and creado_en < limite;
    if s = 0 and a = 0 then continue; end if;
    if s + a <= 0 then continue; end if;                       -- el descuento pasa al siguiente corte
    if exists (select 1 from comision_cortes where operador_id = o.id and fecha_corte = hasta) then continue; end if;
    select max(periodo_hasta) into previo from comision_cortes where operador_id = o.id;
    desde := case when extract(day from hasta) = 15 then date_trunc('month', hasta)::date else date_trunc('month', hasta)::date + 15 end;
    if previo is not null and previo + 1 < desde then desde := previo + 1; end if;
    if previo is null then
      select least(desde, min((creado_en at time zone 'America/Mexico_City')::date)) into desde
        from (select creado_en from comisiones where operador_id = o.id and corte_id is null and cancelada_en is null and creado_en < limite
              union all select creado_en from comision_ajustes where operador_id = o.id and corte_id is null and creado_en < limite) t;
    end if;
    insert into comision_cortes (operador_id, fecha_corte, periodo_desde, periodo_hasta, estado, titular, banco, clabe)
      values (o.id, hasta, desde, hasta, 'enviado', o.titular, o.banco, o.clabe)
      returning * into k;
    update comisiones set corte_id = k.id
      where operador_id = o.id and corte_id is null and cancelada_en is null and creado_en < limite and monto <> 0;
    update comision_ajustes set corte_id = k.id where operador_id = o.id and corte_id is null and creado_en < limite;
    k := corte_recalcular(k.id);
    salida := salida || jsonb_build_object('id', k.id, 'operador_id', o.id, 'total', k.total, 'folio', k.folio);
  end loop;
  return jsonb_build_object('hasta', hasta, 'cortes', salida);
end; $$;
revoke all on function comisiones_generar_cortes(date) from public, anon;
grant execute on function comisiones_generar_cortes(date) to authenticated, service_role;

-- 4. El operador acepta o pide revisión ---------------------------------------------
create or replace function corte_aceptar(p_corte uuid) returns comision_cortes
language plpgsql security definer set search_path = public as $$
declare k comision_cortes; o operadores;
begin
  select * into k from comision_cortes where id = p_corte for update;
  if k.id is null or k.operador_id is distinct from mi_operador() then raise exception 'Ese recibo no es tuyo.'; end if;
  if k.estado <> 'enviado' then raise exception 'Este recibo ya no está esperando tu aceptación.'; end if;
  if k.clabe is null then
    select * into o from operadores where id = k.operador_id;
    if o.clabe is null then raise exception 'Antes de aceptar, captura tu CLABE en «Mi perfil» para que te podamos transferir.'; end if;
    update comision_cortes set titular = o.titular, banco = o.banco, clabe = o.clabe where id = k.id;
  end if;
  update comision_cortes set estado = 'aceptado', aceptado_en = now() where id = k.id returning * into k;
  return k;
end; $$;
revoke all on function corte_aceptar(uuid) from public, anon;
grant execute on function corte_aceptar(uuid) to authenticated;

