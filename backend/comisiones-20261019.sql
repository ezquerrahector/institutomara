--   · Reembolso o contracargo: si la comisión aún no se paga, se cancela (y el recibo
--     se vuelve a mandar para aceptarlo); si ya se pagó, se descuenta del siguiente
--     corte como «Ajuste por reembolso».
--   · Recibo básico: nombre, CLABE y banco, periodo, desglose, ajustes, total y la
--     fecha y hora en que el operador lo aceptó.
--   · El operador acepta («Acepto») o pide revisión («Tengo una duda»). Administración
